# The model source is snapshotted ONCE, at import -- i.e. the exact code this
# process is running. Reading it from disk per run meant a file updated while
# the desk was running produced a script with DIFFERENT code from the server's
# in-memory model, and the self-check refused the run (the server had the old
# rounding, the script had the new half-up rounding -> scores one point apart).
_MODEL_SRC = open(V.__file__, encoding="utf-8").read()


def analysis_script(res, payloads, fx=None):
    src = _MODEL_SRC
    body = src.split('"""', 2)[2]          # drop the module docstring, keep the code
    # The ticker lands inside the generated script, which the desk then RUNS. It comes from UW's data,
    # so it is reduced to ticker characters first: a hostile "symbol" could otherwise close the
    # docstring and execute code (2026-09-26 security review).
    t = re.sub(r"[^A-Z0-9.\-]", "", str(res["fin"]["ticker"]).upper())[:12] or "TICKER"
    # The desk name comes from the dashboard's Settings and lands in a docstring: no quotes or backslashes.
    desk = re.sub(r'["\\\\]', "", brandname.label("valuation", "Valuation Desk")) or "Valuation Desk"
    head = SCRIPT_HEAD.format(desk=desk, ticker=t, stamp=datetime.now().strftime("%Y-%m-%d %H:%M"),
                              version=V.MODEL_VERSION, fname=names(t)["py"])
    tail = SCRIPT_TAIL.format(payloads=json.dumps(payloads, separators=(",", ":")),
                              fx=json.dumps(fx or {}), overrides=json.dumps(res.get("overrides") or {}))
    return head + body + tail


def execute_script(path, timeout=60):
    """Run the generated script with THIS interpreter; return stdout."""
    proc = subprocess.run([sys.executable, path], capture_output=True, text=True,
                          timeout=timeout, encoding="utf-8", errors="replace",
                          env=dict(os.environ, PYTHONIOENCODING="utf-8"))
    if proc.returncode != 0:
        raise RuntimeError("%s exited %d: %s" % (os.path.basename(path), proc.returncode,
                                                  (proc.stderr or "").strip()[-600:]))
    return proc.stdout


def verify_console(res, text):
    """The executed script must reproduce the in-process verdict and base value."""
    want = "VERDICT: %s/10 %s" % (res["score"]["badge"], res["score"]["verdict"])
    if want not in text:
        raise RuntimeError("Generated script did not reproduce the verdict (%s). If the desk "
                           "was updated while running, close the desk window and start it "
                           "again with START_HERE.bat." % want)
    base = V.px(res["valuation"]["scenarios"]["base"]["per_share"])
    if base not in text:
        raise RuntimeError("Generated script did not reproduce the base value %s." % base)


