def _insight(res):
    f, b = res["fin"], res["valuation"]["scenarios"]["base"]
    if res["class"] in ("venture", "growth_burn"):
        return ("The market price needs the bull case: at %s the stock sits %s the bull value of %s, "
                "and the base case requires %s of funding beyond today's cash."
                % (V.px(f["price"]),
                   "above" if (res["valuation"]["scenarios"]["bull"]["upside"] or 0) < 0 else "below",
                   V.px(res["valuation"]["scenarios"]["bull"]["per_share"]),
                   V.money(max(0.0, -(b["min_cum"]) - (f["liquid"] or 0)))))
    implied = None
    for g in [x / 1000 for x in range(-100, 1001, 5)]:
        fin2 = dict(f, rev_growth=g)
        try:
            val = V.value(fin2, res["class"])
        except Exception:
            break
        if val["scenarios"]["base"]["per_share"] and val["scenarios"]["base"]["per_share"] >= f["price"]:
            implied = val["scenarios"]["base"]["growth"]
            break
    if implied is None:
        return ("No growth rate inside this model's bands justifies %s: even the top of the band "
                "leaves the base case short of the price." % V.px(f["price"]))
    return ("To justify %s the base case would need about %s revenue growth for five years, against "
            "%s trailing." % (V.px(f["price"]), V.pct(implied, 0), V.signed_pct(f["rev_growth"])))


