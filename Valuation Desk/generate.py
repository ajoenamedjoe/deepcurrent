def _explain(res):
    """
    The card's method sentence. Must cope with runs saved by OLDER models:
    the history panel re-opens them, and 1.x/2.x results have no "capital"
    block and used a 5-year projection. (Model 3.0 first shipped reading
    v["capital"] unconditionally -> KeyError on the desk's opening page.)
    """
    v, sc = res["valuation"], res["valuation"]["scenarios"]
    cap = v.get("capital")
    years = v.get("years", 5)
    if years > 5:
        horizon = "%d-year projection (5 years at the scenario rate, %d fading)" % (years, years - 5)
    else:
        horizon = "5-year projection"
    if cap is None:
        funding = ""
    elif cap.get("kind") == "roe":
        funding = "growth funded at ROE %.0f%%, " % (100 * cap["value"])
    else:
        funding = "growth funded at sales-to-capital %.1f%s, " % (
            cap["value"], "" if cap.get("from_year", 1) == 1 else " from year %d" % cap["from_year"])
    return ("%s. Discount rate %.1f%%, %s, %sterminal growth 2.5%% (base). Base case grows revenue "
            "%s a year; %s." % (res["method"], 100 * v["discount"], horizon, funding,
                                V.pct(sc["base"]["growth"], 0), res.get("key_driver", "")))


def card(res):
    """Everything the canvas needs, and nothing it would have to derive."""
    f, v, s = res["fin"], res["valuation"], res["score"]
    sc = v["scenarios"]
    growth_lbl = "Revenue growth"
    ratio_lbl, ratio = ("P/E", V.mult(res["multiples"]["pe"])) if res["multiples"]["pe_meaningful"] \
        else ("P/S", V.mult(res["multiples"]["ps"]))
    if res["class"] == "financial":
        # FCF yield is meaningless for a bank (a large bank's can print deeply negative); net margin is not
        cash_lbl, cash = "Net margin", V.pct(f["net_margin"])
    elif res["runway_years"] is not None:
        cash_lbl, cash = "Cash runway", "%.1f yrs" % res["runway_years"]
    else:
        cash_lbl, cash = "FCF yield", V.pct(res["multiples"]["fcf_yield"])
    return {
        "ticker": f["ticker"], "name": f["name"], "sector": f["sector"],
        "class_label": res["class_label"], "method": res["method"],
        "badge": s["badge"], "score": s["score"], "score_uncapped": round(s["valuation_points"] - s["flag_points"], 2), "verdict": s["verdict"], "colour": s["colour"],
        "stance": res["stance"], "verdict_line": res["verdict_line"], "thesis": res["thesis"],
        "price": V.px(f["price"]), "marketcap": V.money(f["marketcap"]),
        "metrics": [
            ["Price", V.px(f["price"]), None],
            [growth_lbl, V.signed_pct(f["rev_growth"]), "good" if (f["rev_growth"] or 0) > 0 else "bad"],
            ["Intrinsic value (base)", V.px(sc["base"]["per_share"]), None],
            ["Operating margin", V.pct(f["op_margin"]), "good" if (f["op_margin"] or 0) > 0 else "bad"],
            ["Upside / downside", V.signed_pct(sc["base"]["upside"]),
             "good" if (sc["base"]["upside"] or 0) >= 0 else "bad"],
            [cash_lbl, cash, None],
            ["Market cap", V.money(f["marketcap"]), None],
            [ratio_lbl, ratio, None],
        ],
        "scenarios": [{"name": k.upper(), "value": V.px(sc[k]["per_share"]),
                       "upside": "net debt > value" if sc[k]["floored"] else V.signed_pct(sc[k]["upside"]),
                       "growth": V.pct(sc[k]["growth"], 0), "up": (sc[k]["upside"] or 0) >= 0,
                       "per_share": sc[k]["per_share"]}
                      for k in ("bull", "base", "bear")],
        "price_num": f["price"],
        "bullets": [{"bad": b["bad"], "text": b["text"]} for b in res["card_bullets"]],
        "carried_by": s["carried_by"][:3],
        "valuation_points": s["valuation_points"], "flag_points": s["flag_points"],
        "explain": _explain(res),
        "summary": [
            ["Business quality", "%s revenue, %s YoY, operating margin %s." % (
                V.money(f["revenue"]), V.signed_pct(f["rev_growth"]), V.pct(f["op_margin"]))],
            ["Valuation", "Base %s vs %s price (%s); bull %s, bear %s." % (
                V.px(sc["base"]["per_share"]), V.px(f["price"]), V.signed_pct(sc["base"]["upside"]),
                V.px(sc["bull"]["per_share"]), V.px(sc["bear"]["per_share"]))],
            ["Philosophy", "Intrinsic value from cash the business can return, with every "
                           "assumption stated. Red flags only ever subtract."],
        ],
        "basis": f["basis"], "overrides": res.get("overrides") or {},
        "model_version": res["model_version"],
        "quality": _card_quality(res),
        "returns": _card_returns(res),
        "gates": [{"key": g["key"], "passed": g["passed"], "applied": g.get("applied", False),
                   "value": g["value"]} for g in (s.get("gates") or [])],
        "why": _card_why(res),
        "synopsis": _synopsis(res),
    }


def _synopsis(res):
    """Stored runs made before the synopsis existed get one computed now, when possible."""
    if res.get("synopsis"):
        return res["synopsis"]
    try:
        return V.synopsis(res)
    except Exception:
        return ""


def _card_quality(res):
    q = res.get("quality")
    if not q:
        return None                       # a run saved before model 3.2
    return {"score": q["score"], "tier": q["tier"], "measured": q["measured"],
            "parts": [[c["label"], c["value"]] for c in q["components"]]}


def _card_returns(res):
    er = (res.get("valuation") or {}).get("returns")
    if not er:
        return None
    irr = er.get("irr") or {}
    g = lambda k: irr.get(k) if k in irr else irr.get(str(k))    # JSON round-trip turns keys into str
    return {"irr5": g(5), "irr10": g(10), "implied_return": er.get("implied_return"),
            "implied_growth": er.get("implied_growth"), "discount": res["valuation"]["discount"]}


def _card_why(res):
    """The one sentence that explains a gated verdict, else the first gate status."""
    lines = res.get("why") or []
    for l in lines:
        if "caps this" in l or "FAILS" in l:
            return l
    return lines[1] if len(lines) > 1 else (lines[0] if lines else "")
